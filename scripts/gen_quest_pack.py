#!/usr/bin/env python3
"""
gen_quest_pack.py — Generate a ZQM Labs quest pack from a YAML config.

Usage:
    python scripts/gen_quest_pack.py path/to/quest.yaml

The quest pack format follows the ZQM Labs quest-authoring spec:
https://github.com/ZQM-Labs/quest-authoring

Output:
    dist/<quest-slug>/index.html — playable quest pack
    dist/<quest-slug>/manifest.json — quest metadata
"""

import json
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("PyYAML required: pip install pyyaml", file=sys.stderr)
    sys.exit(1)


TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{title} — ZQM Labs Quest Pack</title>
  <style>
    body {{ font-family: system-ui, sans-serif; max-width: 800px; margin: 2rem auto; padding: 0 1rem; background: #0a0a0f; color: #e0e0e0; }}
    h1 {{ color: #a855f7; }}
    .stop {{ background: #1a1a2e; border-radius: 12px; padding: 1.5rem; margin: 1rem 0; }}
    .clue {{ color: #fbbf24; font-style: italic; }}
    .answer {{ color: #34d399; }}
    code {{ background: #2a2a3e; padding: 2px 6px; border-radius: 4px; }}
  </style>
</head>
<body>
  <h1>🏮 {title}</h1>
  <p>{description}</p>
  <p><strong>Players:</strong> {players} · <strong>Duration:</strong> {duration} · <strong>Ages:</strong> {ages}</p>
  {stops_html}
  <hr>
  <p><em>Generated by ZQM Labs quest pack generator. <a href="https://github.com/ZQM-Labs/quest-packs" style="color:#a855f7;">View source</a></em></p>
</body>
</html>
"""


def generate_stops_html(stops: list[dict]) -> str:
    """Generate HTML for quest stops."""
    html_parts = []
    for i, stop in enumerate(stops, 1):
        clue = stop.get("clue", "")
        answer = stop.get("answer", "")
        location = stop.get("location", "")
        html_parts.append(f"""
  <div class="stop">
    <h2>Stop {i}: {stop.get('name', f'Stop {i}')}</h2>
    {f'<p><strong>Location:</strong> {location}</p>' if location else ''}
    <p class="clue">🕯️ {clue}</p>
    <p class="answer">💡 Answer: <code>{answer}</code></p>
  </div>""")
    return "\n".join(html_parts)


def main():
    if len(sys.argv) < 2:
        print("Usage: python scripts/gen_quest_pack.py <quest.yaml>", file=sys.stderr)
        sys.exit(1)

    config_path = Path(sys.argv[1])
    if not config_path.exists():
        print(f"Error: {config_path} not found", file=sys.stderr)
        sys.exit(1)

    with open(config_path) as f:
        config = yaml.safe_load(f)

    title = config.get("title", "Untitled Quest")
    description = config.get("description", "")
    players = config.get("players", "2-6")
    duration = config.get("duration", "30-45 min")
    ages = config.get("ages", "8+")
    stops = config.get("stops", [])

    if not stops:
        print("Error: quest must have at least one stop", file=sys.stderr)
        sys.exit(1)

    slug = config.get("slug", title.lower().replace(" ", "-"))
    dist_dir = Path("dist") / slug
    dist_dir.mkdir(parents=True, exist_ok=True)

    # Generate HTML
    html = TEMPLATE.format(
        title=title,
        description=description,
        players=players,
        duration=duration,
        ages=ages,
        stops_html=generate_stops_html(stops),
    )

    (dist_dir / "index.html").write_text(html, encoding="utf-8")

    # Generate manifest
    manifest = {
        "title": title,
        "description": description,
        "players": players,
        "duration": duration,
        "ages": ages,
        "stops": len(stops),
        "slug": slug,
    }
    (dist_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )

    print(f"✅ Generated quest pack: {dist_dir}/")
    print(f"   Title: {title}")
    print(f"   Stops: {len(stops)}")
    print(f"   Players: {players} · Duration: {duration} · Ages: {ages}")


if __name__ == "__main__":
    main()
